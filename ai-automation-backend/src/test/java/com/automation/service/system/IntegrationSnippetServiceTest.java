package com.automation.service.system;

import com.automation.config.InstanceAddress;
import com.automation.entity.OnboardingProfile;
import com.automation.entity.OnboardingProfileType;
import com.automation.entity.Project;
import com.automation.entity.Workflow;
import com.automation.entity.BlockDefinition;
import com.automation.repository.OnboardingProfileRepository;
import com.automation.service.project.OnboardingRenderer;
import com.automation.service.project.ProjectService;
import com.automation.service.workflow.WorkflowService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class IntegrationSnippetServiceTest {

    @Mock
    private OnboardingProfileRepository profileRepository;
    @Mock
    private ProjectService projectService;
    @Mock
    private WorkflowService workflowService;

    private IntegrationSnippetService service;

    @BeforeEach
    void setUp() {
        service = new IntegrationSnippetService(profileRepository, projectService,
                new OnboardingRenderer(profileRepository, workflowService, new InstanceAddress("", "", 9090),
                        com.automation.modules.ModuleRegistry.allEnabled()));
    }

    // --- render: no base profile ---

    @Test
    void render_noBaseProfile_returnsHeaderOnly() {
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());

        String result = service.render(null, null);

        assertThat(result).startsWith("<!-- Auto-generated by MySuricates -->");
        assertThat(result).contains("# MySuricates Integration");
        assertThat(result).endsWith("\n");
    }

    // --- render: with base profile, no project path ---

    @Test
    void render_withBaseProfileNoPath_usesPlaceholderProjectId() {
        OnboardingProfile base = OnboardingProfile.builder()
                .content(Map.of("de", "Project: {{PROJECT_ID}}"))
                .type(OnboardingProfileType.BASE)
                .build();
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of(base));

        String result = service.render(null, "de");

        assertThat(result).contains("Project: <projekt-id>");
    }

    @Test
    void render_withBaseProfileBlankPath_usesPlaceholderProjectId() {
        OnboardingProfile base = OnboardingProfile.builder()
                .content(Map.of("de", "ID={{PROJECT_ID}}"))
                .type(OnboardingProfileType.BASE)
                .build();
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of(base));

        String result = service.render("   ", "de");

        assertThat(result).contains("ID=<projekt-id>");
    }

    // --- render: with base profile and matching project ---

    @Test
    void render_withMatchingProject_replacesProjectId() {
        OnboardingProfile base = OnboardingProfile.builder()
                .content(Map.of("de", "ID={{PROJECT_ID}}"))
                .type(OnboardingProfileType.BASE)
                .build();
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of(base));

        Project project = Project.builder().id("proj-123").path("/my/project").build();
        when(projectService.findAll()).thenReturn(List.of(project));
        when(workflowService.findByProjectId("proj-123")).thenReturn(List.of());

        String result = service.render("/my/project", null);

        assertThat(result).contains("ID=proj-123");
    }

    @Test
    void render_noMatchingProject_usesPlaceholder() {
        OnboardingProfile base = OnboardingProfile.builder()
                .content(Map.of("de", "ID={{PROJECT_ID}}"))
                .type(OnboardingProfileType.BASE)
                .build();
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of(base));
        when(projectService.findAll()).thenReturn(List.of());

        String result = service.render("/nonexistent", "de");

        assertThat(result).contains("ID=<projekt-id>");
    }

    // --- render: workflow list ---

    @Test
    void render_withProjectAndWorkflows_rendersTable() {
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());

        Project project = Project.builder().id("proj-1").path("/test").build();
        when(projectService.findAll()).thenReturn(List.of(project));

        Workflow wf = Workflow.builder()
                .id("wf-1")
                .name("My Workflow")
                .description("Does things")
                .blocks(new ArrayList<>(List.of(
                        BlockDefinition.builder().type("shell").build(),
                        BlockDefinition.builder().type("simple").build()
                )))
                .build();
        when(workflowService.findByProjectId("proj-1")).thenReturn(List.of(wf));

        String result = service.render("/test", "de");

        assertThat(result).contains("## Projekt-Workflows");
        assertThat(result).contains("| My Workflow |");
        assertThat(result).contains("| 2 |");
        assertThat(result).contains("| Does things |");
    }

    @Test
    void render_workflowWithNoBlocks_showsZeroBlockCount() {
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());

        Project project = Project.builder().id("proj-1").path("/test").build();
        when(projectService.findAll()).thenReturn(List.of(project));

        Workflow wf = Workflow.builder()
                .id("wf-1")
                .name("Empty")
                .build();
        wf.setBlocks(null);
        when(workflowService.findByProjectId("proj-1")).thenReturn(List.of(wf));

        String result = service.render("/test", null);

        assertThat(result).contains("| 0 |");
    }

    @Test
    void render_workflowWithNullNameAndDescription_usesDash() {
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());

        Project project = Project.builder().id("proj-1").path("/test").build();
        when(projectService.findAll()).thenReturn(List.of(project));

        Workflow wf = Workflow.builder().id("wf-1").build();
        wf.setName(null);
        wf.setDescription(null);
        when(workflowService.findByProjectId("proj-1")).thenReturn(List.of(wf));

        String result = service.render("/test", null);

        assertThat(result).contains("| \u2014 |");
    }

    @Test
    void render_longDescriptionIsTruncated() {
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());

        Project project = Project.builder().id("proj-1").path("/test").build();
        when(projectService.findAll()).thenReturn(List.of(project));

        String longDesc = "A".repeat(100);
        Workflow wf = Workflow.builder()
                .id("wf-1")
                .name("WF")
                .description(longDesc)
                .build();
        when(workflowService.findByProjectId("proj-1")).thenReturn(List.of(wf));

        String result = service.render("/test", null);

        assertThat(result).contains("AAA...");
        assertThat(result).doesNotContain(longDesc);
    }

    @Test
    void render_descriptionWithPipeIsEscaped() {
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());

        Project project = Project.builder().id("proj-1").path("/test").build();
        when(projectService.findAll()).thenReturn(List.of(project));

        Workflow wf = Workflow.builder()
                .id("wf-1")
                .name("WF")
                .description("A | B")
                .build();
        when(workflowService.findByProjectId("proj-1")).thenReturn(List.of(wf));

        String result = service.render("/test", null);

        assertThat(result).contains("A \\| B");
    }

    @Test
    void render_noWorkflows_showsEmptyWorkflowSectionWithoutTable() {
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());

        Project project = Project.builder().id("proj-1").path("/test").build();
        when(projectService.findAll()).thenReturn(List.of(project));
        when(workflowService.findByProjectId("proj-1")).thenReturn(List.of());

        String result = service.render("/test", "de");

        // Rendered by ProjectOnboardingService like the project file: heading plus an empty note, no table.
        assertThat(result).contains("## Projekt-Workflows");
        assertThat(result).contains("_Noch keine Workflows in diesem Projekt._");
        assertThat(result).doesNotContain("| Workflow |");
    }

    @Test
    void render_outputEndsWithSingleNewline() {
        when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());

        String result = service.render(null, null);

        assertThat(result).endsWith("\n");
        assertThat(result).doesNotEndWith("\n\n");
    }
}
