package com.automation.service.project;

import com.automation.config.InstanceAddress;
import com.automation.dto.request.OnboardingConfigRequest;
import com.automation.entity.OnboardingProfile;
import com.automation.entity.OnboardingProfileType;
import com.automation.entity.Project;
import com.automation.entity.Workflow;
import com.automation.repository.OnboardingProfileRepository;
import com.automation.service.workflow.WorkflowService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.api.io.TempDir;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class ProjectOnboardingServiceTest {

    @Mock private OnboardingProfileRepository profileRepository;
    @Mock private WorkflowService workflowService;
    @Mock private ProjectService projectService;

    private ProjectOnboardingService service;

    @BeforeEach
    void setUp() {
        var modules = com.automation.modules.ModuleRegistry.allEnabled();
        service = new ProjectOnboardingService(
                new OnboardingRenderer(profileRepository, workflowService, new InstanceAddress("", "", 9090), modules),
                modules, projectService);
    }

    private Project buildProject(String id, String path) {
        Project p = new Project();
        p.setId(id);
        p.setName("Test");
        p.setPath(path);
        return p;
    }

    @Nested
    class Enable {

        @Test
        void enable_writesFile(@TempDir Path tempDir) throws Exception {
            Project project = buildProject("p1", tempDir.toString());
            OnboardingProfile base = OnboardingProfile.builder()
                    .key("base").type(OnboardingProfileType.BASE).content(Map.of("de", "Base content {{PROJECT_ID}}")).build();
            when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of(base));
            when(workflowService.findByProjectId("p1")).thenReturn(List.of());

            var config = new OnboardingConfigRequest("CLAUDE_RULES", List.of(), null);
            service.enable(project, config);

            Path expectedFile = tempDir.resolve(".claude/rules/mysuricates.md");
            assertThat(expectedFile).exists();
            assertThat(Files.readString(expectedFile)).contains("Base content p1");
            verify(projectService).updateConfig(eq("p1"), any());
        }

        @Test
        void enable_agentsFormat_writesAgentsMd(@TempDir Path tempDir) {
            Project project = buildProject("p1", tempDir.toString());
            when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());
            when(workflowService.findByProjectId("p1")).thenReturn(List.of());

            var config = new OnboardingConfigRequest("AGENTS_MD", List.of(), null);
            service.enable(project, config);

            assertThat(tempDir.resolve("AGENTS.md")).exists();
        }

        @Test
        void enable_nullPath_noFileWritten() {
            Project project = buildProject("p1", null);
            // writeOnboardingFile returns early for null path, so renderAll is never called

            var config = new OnboardingConfigRequest("CLAUDE_RULES", List.of(), null);
            service.enable(project, config);

            verify(projectService).updateConfig(eq("p1"), any());
        }
    }

    @Nested
    class Disable {

        @Test
        void disable_deletesAutoGeneratedFile(@TempDir Path tempDir) throws Exception {
            Project project = buildProject("p1", tempDir.toString());

            // Create auto-generated file
            Path rulesDir = tempDir.resolve(".claude/rules");
            Files.createDirectories(rulesDir);
            Files.writeString(rulesDir.resolve("mysuricates.md"),
                    "<!-- Auto-generated by MySuricates — do not edit -->\nContent");

            service.disable(project);

            assertThat(rulesDir.resolve("mysuricates.md")).doesNotExist();
            verify(projectService).updateConfig(eq("p1"), any());
        }

        @Test
        void disable_doesNotDeleteManualFile(@TempDir Path tempDir) throws Exception {
            Project project = buildProject("p1", tempDir.toString());

            // Create a manually written file (no auto-generated marker)
            Path rulesDir = tempDir.resolve(".claude/rules");
            Files.createDirectories(rulesDir);
            Files.writeString(rulesDir.resolve("mysuricates.md"), "Manual content here");

            service.disable(project);

            assertThat(rulesDir.resolve("mysuricates.md")).exists();
        }
    }

    @Nested
    class Refresh {

        @Test
        void refresh_enabled_rewritesFile(@TempDir Path tempDir) {
            Project project = buildProject("p1", tempDir.toString());
            Map<String, Object> config = new HashMap<>();
            config.put("onboarding", Map.of("enabled", true, "format", "CLAUDE_RULES"));
            project.setConfig(config);

            when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());
            when(workflowService.findByProjectId("p1")).thenReturn(List.of());

            service.refresh(project);

            assertThat(tempDir.resolve(".claude/rules/mysuricates.md")).exists();
        }

        @Test
        void refresh_disabled_doesNothing(@TempDir Path tempDir) {
            Project project = buildProject("p1", tempDir.toString());
            project.setConfig(Map.of("onboarding", Map.of("enabled", false)));

            service.refresh(project);

            assertThat(tempDir.resolve(".claude/rules/mysuricates.md")).doesNotExist();
        }
    }

    @Nested
    class GetStatus {

        @Test
        void getStatus_enabled_returnsCorrectState(@TempDir Path tempDir) throws Exception {
            Project project = buildProject("p1", tempDir.toString());
            Map<String, Object> config = new HashMap<>();
            config.put("onboarding", Map.of("enabled", true, "format", "CLAUDE_RULES", "profileIds", List.of("prof-1")));
            project.setConfig(config);

            // Create the file
            Path rulesDir = tempDir.resolve(".claude/rules");
            Files.createDirectories(rulesDir);
            Files.writeString(rulesDir.resolve("mysuricates.md"), "content");

            var status = service.getStatus(project);

            assertThat(status.enabled()).isTrue();
            assertThat(status.format()).isEqualTo("CLAUDE_RULES");
            assertThat(status.profileIds()).containsExactly("prof-1");
            assertThat(status.fileExists()).isTrue();
        }

        @Test
        void getStatus_disabled_returnsCorrectState() {
            Project project = buildProject("p1", null);
            project.setConfig(Map.of("onboarding", Map.of("enabled", false)));

            var status = service.getStatus(project);

            assertThat(status.enabled()).isFalse();
            assertThat(status.fileExists()).isFalse();
        }

        @Test
        void getStatus_noConfig_returnsDefaults() {
            Project project = buildProject("p1", null);
            project.setConfig(null);

            var status = service.getStatus(project);

            assertThat(status.enabled()).isFalse();
            assertThat(status.format()).isEqualTo("CLAUDE_RULES");
        }
    }

    @Nested
    class Preview {

        @Test
        void preview_includesBaseAndWorkflows() {
            Project project = buildProject("p1", null);
            project.setConfig(Map.of());

            OnboardingProfile base = OnboardingProfile.builder()
                    .key("base").type(OnboardingProfileType.BASE)
                    .content(Map.of("de", "API reference for {{PROJECT_ID}}")).build();
            when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of(base));

            Workflow wf = Workflow.builder().id("wf-1").name("Test WF").description("Does things")
                    .blocks(List.of()).build();
            when(workflowService.findByProjectId("p1")).thenReturn(List.of(wf));

            String result = service.preview(project);

            assertThat(result).contains("Auto-generated by MySuricates");
            assertThat(result).contains("API reference for p1");
            assertThat(result).contains("Test WF");
            assertThat(result).contains("wf-1");
        }

        @Test
        void preview_withSelectedProfiles() {
            Project project = buildProject("p1", null);
            project.setConfig(Map.of("onboarding", Map.of("profileIds", List.of("prof-dev"))));

            when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());
            OnboardingProfile devProfile = OnboardingProfile.builder()
                    .id("prof-dev").key("developer").content(Map.of("de", "Developer profile content")).build();
            when(profileRepository.findAllById(List.of("prof-dev"))).thenReturn(List.of(devProfile));
            when(workflowService.findByProjectId("p1")).thenReturn(List.of());

            String result = service.preview(project);

            assertThat(result).contains("Developer profile content");
        }

        @Test
        void preview_noWorkflows_showsEmptyMessage() {
            Project project = buildProject("p1", null);
            project.setConfig(Map.of());

            when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());
            when(workflowService.findByProjectId("p1")).thenReturn(List.of());

            String result = service.preview(project);

            assertThat(result).contains("Noch keine Workflows");
        }

        @Test
        void preview_longDescription_truncated() {
            Project project = buildProject("p1", null);
            project.setConfig(Map.of());

            when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());
            Workflow wf = Workflow.builder().id("wf-1").name("WF")
                    .description("x".repeat(100)).blocks(List.of()).build();
            when(workflowService.findByProjectId("p1")).thenReturn(List.of(wf));

            String result = service.preview(project);

            // Description truncated to 80 chars (77 + "...")
            assertThat(result).contains("...");
        }

        @Test
        void preview_descriptionWithPipe_escaped() {
            Project project = buildProject("p1", null);
            project.setConfig(Map.of());

            when(profileRepository.findByType(OnboardingProfileType.BASE)).thenReturn(List.of());
            Workflow wf = Workflow.builder().id("wf-1").name("WF")
                    .description("A | B").blocks(List.of()).build();
            when(workflowService.findByProjectId("p1")).thenReturn(List.of(wf));

            String result = service.preview(project);

            assertThat(result).contains("A \\| B");
        }
    }
}
