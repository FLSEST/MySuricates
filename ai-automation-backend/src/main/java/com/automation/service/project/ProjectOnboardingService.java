package com.automation.service.project;

import com.automation.dto.request.OnboardingConfigRequest;
import com.automation.dto.response.OnboardingStatusResponse;
import com.automation.entity.OnboardingProfile;
import com.automation.entity.OnboardingProfileType;
import com.automation.entity.Project;
import com.automation.entity.Workflow;
import com.automation.repository.OnboardingProfileRepository;
import com.automation.service.workflow.WorkflowService;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;
import java.util.stream.Collectors;

@Service
@RequiredArgsConstructor
@Slf4j
public class ProjectOnboardingService {

    private static final String CLAUDE_RULES_PATH = ".claude/rules/mysuricates.md";
    private static final String AGENTS_MD_PATH = "AGENTS.md";

    private final OnboardingProfileRepository profileRepository;
    private final WorkflowService workflowService;
    private final ProjectService projectService;

    public void enable(Project project, OnboardingConfigRequest config) {
        Map<String, Object> projectConfig = project.getConfig() != null ? new HashMap<>(project.getConfig()) : new HashMap<>();

        Map<String, Object> onboarding = new HashMap<>();
        onboarding.put("enabled", true);
        onboarding.put("format", config.format() != null ? config.format() : "CLAUDE_RULES");
        onboarding.put("profileIds", config.profileIds() != null ? config.profileIds() : List.of());
        projectConfig.put("onboarding", onboarding);

        project.setConfig(projectConfig);
        projectService.updateConfig(project.getId(), projectConfig);

        writeOnboardingFile(project);
    }

    public void disable(Project project) {
        deleteOnboardingFile(project);

        Map<String, Object> projectConfig = project.getConfig() != null ? new HashMap<>(project.getConfig()) : new HashMap<>();
        Map<String, Object> onboarding = new HashMap<>();
        onboarding.put("enabled", false);
        projectConfig.put("onboarding", onboarding);

        project.setConfig(projectConfig);
        projectService.updateConfig(project.getId(), projectConfig);
    }

    public void refresh(Project project) {
        if (!isEnabled(project)) {
            return;
        }
        writeOnboardingFile(project);
    }

    public OnboardingStatusResponse getStatus(Project project) {
        Map<String, Object> onboarding = getOnboardingConfig(project);
        boolean enabled = Boolean.TRUE.equals(onboarding.get("enabled"));
        String format = (String) onboarding.getOrDefault("format", "CLAUDE_RULES");
        @SuppressWarnings("unchecked")
        List<String> profileIds = (List<String>) onboarding.getOrDefault("profileIds", List.of());

        String filePath = resolveRelativePath(format);
        boolean fileExists = false;
        if (enabled && project.getPath() != null) {
            fileExists = Files.exists(Path.of(project.getPath(), filePath));
        }

        return new OnboardingStatusResponse(enabled, format, profileIds, fileExists, filePath);
    }

    public String preview(Project project) {
        return renderAll(project);
    }

    private void writeOnboardingFile(Project project) {
        if (project.getPath() == null || project.getPath().isBlank()) {
            log.debug("No project path — skipping onboarding file write");
            return;
        }

        String format = getFormat(project);
        Path targetFile = Path.of(project.getPath(), resolveRelativePath(format));
        String content = renderAll(project);

        try {
            Files.createDirectories(targetFile.getParent());
            Files.writeString(targetFile, content);
            log.info("Wrote onboarding file to {}", targetFile);
        } catch (IOException e) {
            log.warn("Failed to write onboarding file to {}: {}", targetFile, e.getMessage());
        }
    }

    private void deleteOnboardingFile(Project project) {
        if (project.getPath() == null || project.getPath().isBlank()) {
            return;
        }

        for (String relativePath : List.of(CLAUDE_RULES_PATH, AGENTS_MD_PATH)) {
            Path file = Path.of(project.getPath(), relativePath);
            try {
                if (Files.exists(file)) {
                    String firstLine = Files.readAllLines(file).stream().findFirst().orElse("");
                    if (firstLine.contains("Auto-generated by MySuricates")) {
                        Files.delete(file);
                        log.info("Deleted onboarding file: {}", file);
                    }
                }
            } catch (IOException e) {
                log.debug("Failed to delete onboarding file {}: {}", file, e.getMessage());
            }
        }
    }

    private String renderAll(Project project) {
        StringBuilder sb = new StringBuilder();
        sb.append("<!-- Auto-generated by MySuricates — do not edit -->\n");
        sb.append("# MySuricates Integration\n\n");

        // Layer 1: Base profile
        profileRepository.findByType(OnboardingProfileType.BASE).stream()
                .findFirst()
                .ifPresent(base -> {
                    String content = base.getContent()
                            .replace("{{PROJECT_ID}}", project.getId());
                    sb.append(content).append("\n\n");
                });

        // Layer 2: Selected profiles
        List<String> profileIds = getProfileIds(project);
        if (!profileIds.isEmpty()) {
            List<OnboardingProfile> profiles = profileRepository.findAllById(profileIds);
            if (!profiles.isEmpty()) {
                for (OnboardingProfile profile : profiles) {
                    sb.append(profile.getContent()).append("\n\n");
                }
            }
        }

        // Layer 3: Project workflows
        sb.append(renderWorkflowList(project));

        return sb.toString().stripTrailing() + "\n";
    }

    private String renderWorkflowList(Project project) {
        List<Workflow> workflows = workflowService.findByProjectId(project.getId());
        if (workflows.isEmpty()) {
            return "## Projekt-Workflows\n\n_Noch keine Workflows in diesem Projekt._\n";
        }

        StringBuilder sb = new StringBuilder();
        sb.append("## Projekt-Workflows\n\n");
        sb.append("| Workflow | ID | Blöcke | Beschreibung |\n");
        sb.append("|----------|-------|--------|-------------|\n");

        for (Workflow wf : workflows) {
            String name = wf.getName() != null ? wf.getName() : "—";
            String desc = wf.getDescription() != null ? wf.getDescription().replace("|", "\\|") : "—";
            if (desc.length() > 80) {
                desc = desc.substring(0, 77) + "...";
            }
            int blockCount = wf.getBlocks() != null ? wf.getBlocks().size() : 0;
            sb.append("| ").append(name)
                    .append(" | `").append(wf.getId()).append("`")
                    .append(" | ").append(blockCount)
                    .append(" | ").append(desc)
                    .append(" |\n");
        }

        sb.append("\n### Workflow ausführen\n\n");
        sb.append("```bash\n");
        sb.append("curl -X POST http://localhost:9090/api/v1/workflows/<ID>/execute \\\n");
        sb.append("  -H \"Content-Type: application/json\" \\\n");
        sb.append("  -H \"X-API-Key: <key>\" \\\n");
        sb.append("  -d '{\"context\": {}}'\n");
        sb.append("```\n");

        return sb.toString();
    }

    private boolean isEnabled(Project project) {
        return Boolean.TRUE.equals(getOnboardingConfig(project).get("enabled"));
    }

    private String getFormat(Project project) {
        return (String) getOnboardingConfig(project).getOrDefault("format", "CLAUDE_RULES");
    }

    @SuppressWarnings("unchecked")
    private List<String> getProfileIds(Project project) {
        Object ids = getOnboardingConfig(project).get("profileIds");
        if (ids instanceof List<?> list) {
            return list.stream().map(Object::toString).collect(Collectors.toList());
        }
        return List.of();
    }

    @SuppressWarnings("unchecked")
    private Map<String, Object> getOnboardingConfig(Project project) {
        if (project.getConfig() == null) {
            return Map.of();
        }
        Object onboarding = project.getConfig().get("onboarding");
        if (onboarding instanceof Map<?, ?> map) {
            return (Map<String, Object>) map;
        }
        return Map.of();
    }

    private String resolveRelativePath(String format) {
        return "AGENTS_MD".equals(format) ? AGENTS_MD_PATH : CLAUDE_RULES_PATH;
    }
}
