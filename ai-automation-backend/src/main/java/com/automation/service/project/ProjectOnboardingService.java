package com.automation.service.project;

import com.automation.dto.request.OnboardingConfigRequest;
import com.automation.dto.response.OnboardingStatusResponse;
import com.automation.entity.Project;
import com.automation.modules.ModuleCatalog;
import com.automation.modules.ModuleRegistry;
import com.automation.service.workflow.ProjectWorkflowsChangedEvent;
import com.automation.util.LocalizedJson;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.scheduling.annotation.Async;
import org.springframework.stereotype.Service;
import org.springframework.transaction.event.TransactionPhase;
import org.springframework.transaction.event.TransactionalEventListener;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;
import java.util.function.Predicate;
import java.util.stream.Collectors;

@Service
@RequiredArgsConstructor
@Slf4j
public class ProjectOnboardingService {

    private static final String CLAUDE_RULES_PATH = ".claude/rules/mysuricates.md";
    private static final String AGENTS_MD_PATH = "AGENTS.md";
    /** First line of every file this service writes; only such files are ever overwritten or deleted. */
    static final String MARKER = "Auto-generated by MySuricates";
    /** Language of projects that enabled onboarding before it was bilingual: their text was German. */
    static final String LEGACY_LANGUAGE = "de";

    private final OnboardingRenderer renderer;
    private final ModuleRegistry modules;
    private final ProjectService projectService;

    public void enable(Project project, OnboardingConfigRequest config) {
        String previousFormat = isEnabled(project) ? getFormat(project) : null;
        Map<String, Object> projectConfig = project.getConfig() != null ? new HashMap<>(project.getConfig()) : new HashMap<>();

        Map<String, Object> onboarding = new HashMap<>();
        onboarding.put("enabled", true);
        onboarding.put("format", config.format() != null ? config.format() : "CLAUDE_RULES");
        onboarding.put("profileIds", config.profileIds() != null ? config.profileIds() : List.of());
        onboarding.put("language", config.language() != null
                ? LocalizedJson.normalize(config.language())
                : getLanguage(project));
        projectConfig.put("onboarding", onboarding);

        project.setConfig(projectConfig);
        projectService.updateConfig(project.getId(), projectConfig);

        writeOnboardingFile(project);
        // Switching the format leaves the file of the old one behind otherwise (only ours is removed).
        if (previousFormat != null && !previousFormat.equals(getFormat(project))) {
            deleteOwnFile(project, resolveRelativePath(previousFormat));
        }
    }

    public void disable(Project project) {
        deleteOnboardingFile(project);

        Map<String, Object> projectConfig = project.getConfig() != null ? new HashMap<>(project.getConfig()) : new HashMap<>();
        Map<String, Object> onboarding = new HashMap<>();
        onboarding.put("enabled", false);
        projectConfig.put("onboarding", onboarding);

        project.setConfig(projectConfig);
        projectService.updateConfig(project.getId(), projectConfig);
    }

    public void refresh(Project project) {
        if (!isEnabled(project)) {
            return;
        }
        writeOnboardingFile(project);
    }

    public OnboardingStatusResponse getStatus(Project project) {
        Map<String, Object> onboarding = getOnboardingConfig(project);
        boolean enabled = Boolean.TRUE.equals(onboarding.get("enabled"));
        String format = (String) onboarding.getOrDefault("format", "CLAUDE_RULES");
        @SuppressWarnings("unchecked")
        List<String> profileIds = (List<String>) onboarding.getOrDefault("profileIds", List.of());

        String filePath = resolveRelativePath(format);
        boolean fileExists = false;
        boolean fileForeign = false;
        if (enabled && project.getPath() != null) {
            Path file = Path.of(project.getPath(), filePath);
            fileExists = Files.exists(file);
            fileForeign = fileExists && !writtenByUs(file);
        }

        return new OnboardingStatusResponse(enabled, format, profileIds, fileExists, filePath,
                getLanguage(project), fileForeign);
    }

    public String preview(Project project) {
        return renderer.render(project, getLanguage(project), getProfileIds(project));
    }

    private void writeOnboardingFile(Project project) {
        if (project.getPath() == null || project.getPath().isBlank()) {
            log.debug("No project path — skipping onboarding file write");
            return;
        }

        String format = getFormat(project);
        Path targetFile = Path.of(project.getPath(), resolveRelativePath(format));
        String content = renderer.render(project, getLanguage(project), getProfileIds(project));

        // A hand-written AGENTS.md (or rules file) is the project's own — never overwritten.
        if (Files.exists(targetFile) && !writtenByUs(targetFile)) {
            log.warn("Onboarding file {} exists without the MySuricates marker — not overwritten", targetFile);
            return;
        }

        try {
            Files.createDirectories(targetFile.getParent());
            Files.writeString(targetFile, content);
            log.info("Wrote onboarding file to {}", targetFile);
        } catch (IOException e) {
            log.warn("Failed to write onboarding file to {}: {}", targetFile, e.getMessage());
        }
    }

    private void deleteOnboardingFile(Project project) {
        if (project.getPath() == null || project.getPath().isBlank()) {
            return;
        }

        for (String relativePath : List.of(CLAUDE_RULES_PATH, AGENTS_MD_PATH)) {
            deleteOwnFile(project, relativePath);
        }
    }

    private void deleteOwnFile(Project project, String relativePath) {
        if (project.getPath() == null || project.getPath().isBlank()) {
            return;
        }
        Path file = Path.of(project.getPath(), relativePath);
        try {
            if (Files.exists(file) && writtenByUs(file)) {
                Files.delete(file);
                log.info("Deleted onboarding file: {}", file);
            }
        } catch (IOException e) {
            log.debug("Failed to delete onboarding file {}: {}", file, e.getMessage());
        }
    }

    /** A project's workflows changed: its file lists them (TODO 644fd5ad). After the commit, so the list is current. */
    @Async
    @TransactionalEventListener(phase = TransactionPhase.AFTER_COMMIT, fallbackExecution = true)
    public void onProjectWorkflowsChanged(ProjectWorkflowsChangedEvent event) {
        refreshEnabled(project -> project.getId().equals(event.projectId()));
    }

    /** A profile's text changed: every file that includes it is written again. */
    @Async
    @TransactionalEventListener(phase = TransactionPhase.AFTER_COMMIT, fallbackExecution = true)
    public void onProfileChanged(OnboardingProfileChangedEvent event) {
        refreshEnabled(project -> event.base() || getProfileIds(project).contains(event.profileId()));
    }

    /**
     * Writes the file again for every project with onboarding switched on that {@code filter} accepts.
     * Nothing while the module is off — the files stay as they are, nothing is deleted.
     *
     * @return how many projects were refreshed
     */
    public int refreshEnabled(Predicate<Project> filter) {
        if (!modules.isEnabled(ModuleCatalog.ONBOARDING_PROFILES)) {
            return 0;
        }
        int refreshed = 0;
        for (Project project : projectService.findAll()) {
            try {
                if (isEnabled(project) && filter.test(project)) {
                    writeOnboardingFile(project);
                    refreshed++;
                }
            } catch (RuntimeException e) {
                log.warn("Failed to refresh onboarding file of project {}: {}", project.getId(), e.getMessage());
            }
        }
        return refreshed;
    }

    private boolean isEnabled(Project project) {
        return Boolean.TRUE.equals(getOnboardingConfig(project).get("enabled"));
    }

    /** Language of the written text; projects from before V81 keep German. */
    String getLanguage(Project project) {
        Object language = getOnboardingConfig(project).get("language");
        return language instanceof String lang && !lang.isBlank()
                ? LocalizedJson.normalize(lang)
                : LEGACY_LANGUAGE;
    }

    private static boolean writtenByUs(Path file) {
        try (var lines = Files.lines(file)) {
            return lines.findFirst().map(line -> line.contains(MARKER)).orElse(false);
        } catch (IOException | java.io.UncheckedIOException e) {
            return false;
        }
    }

    private String getFormat(Project project) {
        return (String) getOnboardingConfig(project).getOrDefault("format", "CLAUDE_RULES");
    }

    @SuppressWarnings("unchecked")
    private List<String> getProfileIds(Project project) {
        Object ids = getOnboardingConfig(project).get("profileIds");
        if (ids instanceof List<?> list) {
            return list.stream().map(Object::toString).collect(Collectors.toList());
        }
        return List.of();
    }

    @SuppressWarnings("unchecked")
    private Map<String, Object> getOnboardingConfig(Project project) {
        if (project.getConfig() == null) {
            return Map.of();
        }
        Object onboarding = project.getConfig().get("onboarding");
        if (onboarding instanceof Map<?, ?> map) {
            return (Map<String, Object>) map;
        }
        return Map.of();
    }

    private String resolveRelativePath(String format) {
        return "AGENTS_MD".equals(format) ? AGENTS_MD_PATH : CLAUDE_RULES_PATH;
    }
}
