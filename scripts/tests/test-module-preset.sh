#!/usr/bin/env bash
# Tests for scripts/lib/module-preset.sh — preset validation and the local config writer.
# Run: bash scripts/tests/test-module-preset.sh   (exit 0 = all passed)
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/module-preset.sh
source "$HERE/../lib/module-preset.sh"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
PASS=0; FAIL=0

check() {  # $1 = label, $2 = shell condition
  if eval "$2"; then echo "  ok   $1"; PASS=$((PASS + 1)); else echo "  FAIL $1"; FAIL=$((FAIL + 1)); fi
}

# Reads automation.modules.preset the way a YAML parser sees it — the check that a written file still means
# what it should. Without PyYAML (not required) the function returns "skipped", the corresponding
# check then runs into nothing instead of going falsely red.
HAVE_YAML=0; python3 -c 'import yaml' 2>/dev/null && HAVE_YAML=1
yaml_preset() {
  [ "$HAVE_YAML" = 1 ] || { echo skipped; return 0; }
  python3 -c 'import sys,yaml; d=yaml.safe_load(open(sys.argv[1])) or {}; print(((d.get("automation") or {}).get("modules") or {}).get("preset"))' "$1" 2>/dev/null
}
yaml_expect() {  # $1 = file, $2 = expected preset
  local got; got="$(yaml_preset "$1")"
  [ "$got" = "$2" ] || [ "$got" = skipped ]
}

echo "1) validation"
check "core, research and full are valid"  'module_preset_valid core && module_preset_valid research && module_preset_valid full'
check "unknown and empty presets are rejected" '! module_preset_valid everything && ! module_preset_valid ""'

echo "2) writing the local config"
CFG="$TMP/backend/config/application.yml"
module_preset_write "$CFG" research; RC=$?
check "writes a new file (rc=$RC)"                    '[ "$RC" -eq 0 ] && [ -f "$CFG" ]'
check "creates the config directory"                  '[ -d "$TMP/backend/config" ]'
check "contains the preset under automation.modules"  'grep -q "^automation:$" "$CFG" && grep -q "^  modules:$" "$CFG" && grep -q "^    preset: research$" "$CFG"'
check "explains how to override single modules"       'grep -q "automation.modules.webhooks: true" "$CFG"'

echo "3) never overwrites"
echo "automation.modules.preset: full  # user edited" > "$CFG"
module_preset_write "$CFG" core; RC=$?
check "existing file returns 3"                       '[ "$RC" -eq 3 ]'
check "existing content is untouched"                 'grep -q "user edited" "$CFG" && ! grep -q "preset: core" "$CFG"'

echo "4) bad preset"
module_preset_write "$TMP/other.yml" nope; RC=$?
check "bad preset returns 2 and writes nothing"       '[ "$RC" -eq 2 ] && [ ! -e "$TMP/other.yml" ]'

echo "5) prompt mapping"
check "1 → core"            '[ "$(module_preset_prompt core <<<"1" 2>/dev/null)" = core ]'
check "3 → full"            '[ "$(module_preset_prompt core <<<"3" 2>/dev/null)" = full ]'
check "Enter → default"     '[ "$(module_preset_prompt research <<<"" 2>/dev/null)" = research ]'
check "garbage → default"   '[ "$(module_preset_prompt core <<<"x" 2>/dev/null)" = core ]'

echo "6) setup.sh argument handling"
SETUP="$HERE/../setup.sh"
check "--help documents --preset"                     'bash "$SETUP" --help | grep -- "--preset core" >/dev/null'
check "--help documents --lang"                       'bash "$SETUP" --help | grep -- "--lang de" >/dev/null'
check "unknown preset exits 2 before any check"       'bash "$SETUP" --preset everything >/dev/null 2>&1; [ $? -eq 2 ]'

echo "7) generated module catalog"
GENERATED="$HERE/../lib/module-catalog.generated.sh"
check "the generated file exists"                     '[ -f "$GENERATED" ]'
check "the generated file parses (bash -n)"           'bash -n "$GENERATED"'
check "says it is generated, not hand-written"        'grep -q "generated by ModuleCatalogTextsTest" "$GENERATED"'
check "keys = feature keys + hardening keys"          '[ "${#MODULE_CATALOG_KEYS[@]}" -eq $(( ${#MODULE_CATALOG_FEATURE_KEYS[@]} + ${#MODULE_CATALOG_HARDENING_KEYS[@]} )) ]'
check "carries tier, risks and requires"              '[ "$(module_catalog_get TIER remote-access)" = advanced ] && [ "$(module_catalog_get RISKS terminal)" = host-access ] && [ "$(module_catalog_get REQUIRES sealing)" = provenance ]'
check "every key has a name in every language"        '( for l in "${MODULE_CATALOG_LANGS[@]}"; do for k in "${MODULE_CATALOG_KEYS[@]}"; do [ -n "$(module_text_get NAME "$l" "$k")" ] && [ -n "$(module_text_get DESC "$l" "$k")" ] || exit 1; done; done )'
check "bash 3.2: no associative arrays anywhere"      '! grep -nE "declare -g?A|mapfile|readarray" "$GENERATED" "$HERE/../lib/module-preset.sh"'

echo "8) language choice (--lang / \$LANG, fallback en)"
check "--lang de wins"                                '[ "$(module_text_lang de)" = de ]'
check "--lang en wins"                                '[ "$(module_text_lang en)" = en ]'
check "unknown --lang falls back to en"               '[ "$(module_text_lang fr)" = en ]'
check "no flag: LANG prefix decides"                  '[ "$(LANG=de_DE.UTF-8 module_text_lang)" = de ]'
check "no flag: LANG=fr_FR falls back to en"          '[ "$(LANG=fr_FR module_text_lang)" = en ]'
check "no flag and no LANG falls back to en"          '[ "$(LANG= LC_ALL= LC_MESSAGES= module_text_lang)" = en ]'
check "LC_ALL beats LANG"                             '[ "$(LC_ALL=de_DE.UTF-8 LANG=fr_FR module_text_lang)" = de ]'
check "unknown module key falls back to the key"      '[ "$(module_text_name nope de)" = nope ] && [ -z "$(module_text_desc nope de)" ]'

echo "9) the preset prompt shows the module texts"
# The menu goes to stderr, the chosen preset to stdout — capture stderr only. No pipe into
# grep: with pipefail an early-exiting grep would SIGPIPE the writer and fail the check.
menu() { module_preset_prompt core "${1:-}" <<<"" 2>&1 >/dev/null; }
MENU_DE="$(menu de)"
MENU_FALLBACK="$(LANG=fr_FR menu)"
check "--lang de shows German names"                  '[[ "$MENU_DE" == *Fernzugriff* ]]'
check "--lang de shows German descriptions"           '[[ "$MENU_DE" == *"über Tailscale"* ]]'
check "--lang de lists the research modules"          '[[ "$MENU_DE" == *Workflow-Memory* ]]'
check "--lang de speaks German around the list"       '[[ "$MENU_DE" == *"Welche Module"* ]]'
check "no flag + LANG=fr_FR shows English"            '[[ "$MENU_FALLBACK" == *"Remote access"* ]]'
check "no flag + LANG=fr_FR has no German text"       '[[ "$MENU_FALLBACK" != *Fernzugriff* ]]'
check "no flag + LANG=fr_FR speaks English"           '[[ "$MENU_FALLBACK" == *"Which modules"* ]]'
check "every feature module is offered exactly once"  '[ "$(printf "%s\n" "$MENU_DE" | grep -c "^ \{9\}[^ ].* — ")" -eq "${#MODULE_CATALOG_FEATURE_KEYS[@]}" ]'
check "the language never changes the result"         '[ "$(LANG=fr_FR module_preset_prompt research <<<"" 2>/dev/null)" = research ]'

echo "10) the comment header of the written config follows --lang (TODO 7c90b447)"
CFG_EN="$TMP/backend-en/config/application.yml"
module_preset_write "$CFG_EN" core en; RC=$?
check "writes with rc=0"                              '[ "$RC" -eq 0 ]'
check "header text is English"                        'grep -q "^# Local override config" "$CFG_EN"'
check "still explains how to override single modules" 'grep -q "automation.modules.webhooks: true" "$CFG_EN"'
check "no German header text leaks in"                '! grep -q "Lokale Override-Config" "$CFG_EN"'

CFG_DE="$TMP/backend-de/config/application.yml"
module_preset_write "$CFG_DE" core de; RC=$?
check "writes with rc=0"                              '[ "$RC" -eq 0 ]'
check "header text is German"                         'grep -q "^# Lokale Override-Config" "$CFG_DE"'

CFG_DEFAULT="$TMP/backend-default/config/application.yml"
module_preset_write "$CFG_DEFAULT" core; RC=$?
check "no lang argument keeps the German default"     'grep -q "^# Lokale Override-Config" "$CFG_DEFAULT"'

echo "11) module_preset_update: nur die Preset-Zeile einer vorhandenen Datei (TODO 729ceb19)"
UPD="$TMP/upd/config/application.yml"
mkdir -p "$(dirname "$UPD")"
write_existing() {  # $1 = target file
  cat > "$1" <<'YAML'
# Lokale Override-Config (nicht im Git).
automation:
  modules:
    preset: core   # von Hand gesetzt
    webhooks: true
  hardening:
    sealing: true
logging:
  level:
    com.automation: DEBUG
YAML
}
write_existing "$UPD"; cp "$UPD" "$TMP/upd.orig"
module_preset_update "$UPD" full; RC=$?
check "updates an existing file (rc=$RC)"             '[ "$RC" -eq 0 ]'
check "the preset line now names the new preset"      'grep -q "^    preset: full" "$UPD"'
check "keeps the trailing comment of that line"       'grep -q "^    preset: full   # von Hand gesetzt$" "$UPD"'
check "everything else is byte-identical"             'diff <(sed "s/^    preset: core   /    preset: full   /" "$TMP/upd.orig") "$UPD" >/dev/null'
check "no config header is prepended"                 '[ "$(grep -c "^# Lokale Override-Config" "$UPD")" -eq 1 ]'

echo "12) module_preset_update: fehlende Preset-Zeile wird ergaenzt"
ADD1="$TMP/add1/config/application.yml"; mkdir -p "$(dirname "$ADD1")"
printf 'automation:\n  modules:\n    webhooks: true\n  hardening:\n    sealing: true\n' > "$ADD1"
module_preset_update "$ADD1" research; RC=$?
check "adds the line under automation.modules (rc=$RC)" '[ "$RC" -eq 0 ] && grep -q "^    preset: research$" "$ADD1"'
check "keeps the other module values"                  'grep -q "^    webhooks: true$" "$ADD1" && grep -q "^    sealing: true$" "$ADD1"'

ADD2="$TMP/add2/config/application.yml"; mkdir -p "$(dirname "$ADD2")"
printf 'automation:\n  host-claude:\n    timeout-seconds: 600\n' > "$ADD2"
module_preset_update "$ADD2" core; RC=$?
check "adds modules: under an existing automation: (rc=$RC)" '[ "$RC" -eq 0 ] && grep -q "^  modules:$" "$ADD2" && grep -q "^    preset: core$" "$ADD2"'
check "keeps the existing automation values"                 'grep -q "^    timeout-seconds: 600$" "$ADD2"'

ADD3="$TMP/add3/config/application.yml"; mkdir -p "$(dirname "$ADD3")"
printf 'logging:\n  level:\n    root: INFO\n' > "$ADD3"
module_preset_update "$ADD3" full; RC=$?
check "appends a whole automation block (rc=$RC)"      '[ "$RC" -eq 0 ] && grep -q "^automation:$" "$ADD3" && grep -q "^    preset: full$" "$ADD3"'
check "the appended block parses as the preset"        'yaml_expect "$ADD3" full'
check "keeps the unrelated top-level keys"             'grep -q "^logging:$" "$ADD3" && grep -q "^    root: INFO$" "$ADD3"'

echo "13) module_preset_update: Abbruch statt Raten"
DUP="$TMP/dup.yml"
printf 'automation:\n  modules:\n    preset: core\nautomation:\n  modules:\n    preset: full\n' > "$DUP"
cp "$DUP" "$TMP/dup.orig"
module_preset_update "$DUP" research 2>/dev/null; RC=$?
check "two preset lines abort (rc=$RC, nothing written)" '[ "$RC" -eq 5 ] && diff "$TMP/dup.orig" "$DUP" >/dev/null'
SCALAR="$TMP/scalar.yml"
printf 'automation:\n  modules: core\n' > "$SCALAR"; cp "$SCALAR" "$TMP/scalar.orig"
module_preset_update "$SCALAR" full 2>/dev/null; RC=$?
check "a scalar automation.modules aborts (rc=$RC)"     '[ "$RC" -eq 5 ] && diff "$TMP/scalar.orig" "$SCALAR" >/dev/null'
CRLF="$TMP/crlf.yml"
printf 'automation:\r\n  modules:\r\n    preset: core\r\n' > "$CRLF"; cp "$CRLF" "$TMP/crlf.orig"
module_preset_update "$CRLF" full; RC=$?
# CRLF must not lead to no line being recognised as a key and a second automation: block being
# appended — Spring reads with allowDuplicateKeys(false) and would then no longer start
# (review fix round 1).
check "CRLF: nur die Preset-Zeile geaendert (rc=$RC)"   '[ "$RC" -eq 0 ] && [ "$(grep -c "^automation:" "$CRLF")" -eq 1 ]'
check "CRLF: der neue Wert steht drin"                  'grep -q "preset: full" "$CRLF"'
check "CRLF: ein Parser liest das neue Preset"          'yaml_expect "$CRLF" full'
check "CRLF: die Zeilenenden bleiben CRLF"              '[ "$(grep -c $'\''\r$'\'' "$CRLF")" -eq 3 ]'
NOKEY="$TMP/nokey.yml"
printf -- '- eins\n- zwei\n' > "$NOKEY"; cp "$NOKEY" "$TMP/nokey.orig"
module_preset_update "$NOKEY" full 2>/dev/null; RC=$?
check "Inhalt ohne erkennbaren Schluessel bricht ab (rc=$RC)" '[ "$RC" -eq 5 ] && diff "$TMP/nokey.orig" "$NOKEY" >/dev/null'
EMPTYVAL="$TMP/emptyval.yml"
printf 'automation:\n  modules:\n    preset:\n' > "$EMPTYVAL"
module_preset_update "$EMPTYVAL" research; RC=$?
# Without a space the result would be "preset:research" — YAML reads that as a key scalar.
check "leerer Preset-Wert bekommt ein Leerzeichen (rc=$RC)" '[ "$RC" -eq 0 ] && grep -q "^    preset: research$" "$EMPTYVAL"'
check "und ein Parser liest research"                       'yaml_expect "$EMPTYVAL" research'
EMPTYCOMMENT="$TMP/emptycomment.yml"
printf 'automation:\n  modules:\n    preset:   # spaeter setzen\n' > "$EMPTYCOMMENT"
module_preset_update "$EMPTYCOMMENT" full; RC=$?
# A space before the value and before the # — otherwise the value would be "full#..." instead of "full".
check "leerer Wert mit Kommentar bleibt lesbar (rc=$RC)"    '[ "$RC" -eq 0 ] && grep -q "^    preset:  *full  *# spaeter setzen$" "$EMPTYCOMMENT"'
check "und ein Parser liest full, nicht full#..."           'yaml_expect "$EMPTYCOMMENT" full'
RO="$TMP/readonly.yml"
printf 'automation:\n  modules:\n    preset: core\n' > "$RO"; cp "$RO" "$TMP/readonly.orig"; chmod a-w "$RO"
ERR="$(module_preset_update "$RO" full 2>&1)"; RC=$?
chmod u+w "$RO"
check "nicht schreibbare Datei meldet rc 1"             '[ "$RC" -eq 1 ] && diff "$TMP/readonly.orig" "$RO" >/dev/null'
check "und nennt den Grund statt einer Bash-Meldung"    '[[ "$ERR" == *module_preset_update* ]] && [[ "$ERR" != *"Permission denied"* ]]'
module_preset_update "$TMP/missing.yml" core 2>/dev/null; RC=$?
check "a missing file returns 4 and writes nothing"     '[ "$RC" -eq 4 ] && [ ! -e "$TMP/missing.yml" ]'
BAD="$TMP/bad.yml"; printf 'automation:\n  modules:\n    preset: core\n' > "$BAD"; cp "$BAD" "$TMP/bad.orig"
module_preset_update "$BAD" nope 2>/dev/null; RC=$?
check "a bad preset returns 2 and writes nothing"       '[ "$RC" -eq 2 ] && diff "$TMP/bad.orig" "$BAD" >/dev/null'

echo "14) setup.sh --force"
FORCED="$TMP/forced/config/application.yml"; mkdir -p "$(dirname "$FORCED")"
write_existing "$FORCED"; cp "$FORCED" "$TMP/forced.orig"
check "--help documents --force"                       'bash "$SETUP" --help | grep -- "--force" >/dev/null'
check "--force without --preset exits 2 and says why"  'out="$(bash "$SETUP" --force 2>&1 >/dev/null)"; [ $? -eq 2 ] && [[ "$out" == *"--preset"* ]]'
# Without the flag the old behaviour stays: module_preset_write leaves the file alone.
module_preset_write "$FORCED" full; RC=$?
check "without the flag the file is untouched (rc=$RC)" '[ "$RC" -eq 3 ] && diff "$TMP/forced.orig" "$FORCED" >/dev/null'

echo
echo "passed: $PASS, failed: $FAIL"
[ "$FAIL" -eq 0 ]
