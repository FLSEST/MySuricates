#!/usr/bin/env bash
# Compose override with exactly the mounts THIS machine has — for every container way of running
# MySuricates (deploy/compose.yml via scripts/instance.sh, and the dev container of
# start-autotrigger-dev.sh). Hard-wired mounts break the start on every machine that lacks one of
# them (TODO fc9de67b); this file is the one place that decides what exists.
#
# Linux: the AI CLIs themselves AND their logins come from the host, so nobody logs in twice
# (Flo, 2026-09-21). macOS: a Mac binary does not run in a Linux container — only the logins are
# mounted; the CLIs have to come from the image (not built in yet — TODO 3dd32594). bash 3.2 (macOS).

HOST_MOUNTS_PROVIDER_COUNT=0

# host_mounts_yaml SERVICE PROJECTS_DIR DOCKER_SOCKET
host_mounts_yaml() {
  local service="$1" projects="${2:-}" socket="${3:-0}"
  local os="${HOST_MOUNTS_OS:-$(uname -s)}" nm="${HOST_MOUNTS_NODE_MODULES:-/usr/lib/node_modules}"
  local lines="" p
  HOST_MOUNTS_PROVIDER_COUNT=0
  _hm_add() { lines="${lines}      - $1
"; }

  # Claude: binary link + versions (Linux only), login dir, startup state seeded read-only
  # (entrypoint copies /seed/.claude.json to a writable place).
  if [ "$os" = "Linux" ]; then
    for p in "$HOME/.local/bin" "$HOME/.local/share/claude"; do
      [ -e "$p" ] && _hm_add "$p:$p:ro"
    done
  fi
  [ -f "$HOME/.claude.json" ] && _hm_add "$HOME/.claude.json:/seed/.claude.json:ro"
  if [ -d "$HOME/.claude" ]; then _hm_add "$HOME/.claude:$HOME/.claude"; HOST_MOUNTS_PROVIDER_COUNT=$((HOST_MOUNTS_PROVIDER_COUNT + 1)); fi

  # Codex and Pi: npm packages OUTSIDE $HOME (Linux only) + login dirs.
  if [ "$os" = "Linux" ]; then
    for p in "$nm/@openai/codex" "$nm/@earendil-works/pi-coding-agent"; do
      [ -d "$p" ] && _hm_add "$p:$p:ro"
    done
  fi
  for p in "$HOME/.codex" "$HOME/.pi"; do
    if [ -d "$p" ]; then _hm_add "$p:$p"; HOST_MOUNTS_PROVIDER_COUNT=$((HOST_MOUNTS_PROVIDER_COUNT + 1)); fi
  done

  # Projects: same path inside as outside, so project paths stored in the DB stay valid.
  # Never the whole home directory.
  if [ -n "$projects" ] && [ -d "$projects" ]; then
    projects="$(cd "$projects" && pwd)"
    if [ "$projects" != "$(cd "$HOME" && pwd)" ]; then _hm_add "$projects:$projects"; fi
  fi

  # Docker socket only on request: it gives the instance full control over the host's Docker.
  [ "$socket" = "1" ] && [ -S /var/run/docker.sock -o -n "${HOST_MOUNTS_ASSUME_SOCKET:-}" ] \
    && _hm_add "/var/run/docker.sock:/var/run/docker.sock"

  echo "# Generated by scripts/lib/host-mounts.sh — do not edit."
  echo "services:"
  echo "  ${service}:"
  if [ -z "$lines" ]; then
    echo "    volumes: []"
  else
    echo "    volumes:"
    printf '%s' "$lines"
  fi
  unset -f _hm_add
}
