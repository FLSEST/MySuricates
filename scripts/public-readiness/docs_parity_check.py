#!/usr/bin/env python3
"""Deterministic docs check: dead links and DE/EN parity (TODO c58d7402).

Four things a machine checks better than a read-through:

1. **Dead targets** — every relative Markdown link in a tracked .md points to an
   existing file.
2. **Dead anchors** — the fragment after `#` matches a heading of the target file,
   following GitHub's slug rules.
3. **DE/EN parity** — every `docs/*.md` has a counterpart under `docs/en/`, and both
   carry the same sequence of heading levels. The same one level deeper for the
   folders in `MIRRORED_SUBDIRS` (`docs/konzepte/x.md` <-> `docs/en/konzepte/x.md`). If the
   sequence differs, `align_sections` pairs the sections by their content and names exactly
   those without a counterpart (TODO 2d553479).
4. **Generated references** — the pages `scripts/docs-reference.py` generates from the code
   (API reference, block reference) match their source (`--check`, TODO 1ab3ad21). So a new
   endpoint or config key without a regenerated page shows up wherever this gate runs — in the
   pre-push too.

What is NOT checked here, because it takes judgement: being up to date with the code
(that is doc-facts-check.sh) and comprehensibility for outsiders (that is the workflow
"Doku-Durchsicht").

Known, ticketed gaps are listed in KNOWN_GAPS. They do not turn the gate red — a
*new* gap does. Without this list the gate would sit on YELLOW permanently and be worthless
as a signal; exactly the mistake docs-check.sh had until 2026-09-20.

Generated pages (point 4) are also checked for links and DE/EN parity like any other page; their
templates under scripts/docs-reference/ are not (see TEMPLATE_PREFIXES).

Run:  python3 scripts/public-readiness/docs_parity_check.py
      python3 scripts/public-readiness/docs_parity_check.py --root <dir>
Exit: 0 = no new findings, 1 = new findings
"""
from __future__ import annotations

import argparse
import difflib
import os
import re
import subprocess
import sys
from pathlib import Path

# The script's own directory must go on the path: tests load this script via
# spec_from_file_location, and its directory is then not on sys.path.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from md_common import FENCE, headings, iter_links, slug, tracked_markdown  # noqa: E402

# Subfolders of docs/ that are mirrored one to one under docs/en/, like docs/ itself.
# Deliberately a list instead of "whatever exists under docs/en/": otherwise a folder whose
# English version is missing entirely would stay invisible — that is how docs/konzepte/ went unnoticed (TODO b94beaed).
MIRRORED_SUBDIRS: tuple[str, ...] = ("konzepte",)  # docs/onboarding/ dropped in the docs rework (TODO 1ab3ad21)

# Known, ticketed gaps. Format: path -> reason with TODO id.
# Currently empty: the ten diagram pages that were listed here have had an English
# counterpart since TODO 47bd4d27 — generated by scripts/docs-diagrams.py from the same source.
KNOWN_GAPS: dict[str, str] = {}

# Templates of the generated reference pages (scripts/docs-reference/<page>.<de|en>.md). Their relative
# links only hold at the target under docs/ or docs/en/ and are checked there, not here.
TEMPLATE_PREFIXES: tuple[str, ...] = ("scripts/docs-reference/",)

# The generator of the reference pages; called with --root so tests can point it at fixtures.
REFERENCE_SCRIPT = Path(__file__).resolve().parents[1] / "docs-reference.py"

# Individual sections without a counterpart. Format: "file::heading" -> TODO id.
# The key is the heading that is REALLY missing: until TODO 2d553479 the check compared
# only the sequence of levels and attributed a gap to the last section of the same rank. So
# this held "entwicklung.md::## Bekannte Einschränkungen" (missing was "## Diagramm-Seiten")
# and "architektur.md::## Completion Triggers (V39)" (missing was the Audit Center, since TODO
# 49f15990 translated). Currently empty: "## Scheduler: verpasste Termine" has been
# translated since TODO c58d7402.
KNOWN_SECTION_GAPS: dict[str, str] = {}


def check_links(root: Path, files: list[str]) -> tuple[list[str], int]:
    findings: list[str] = []
    checked = 0
    for rel in files:
        path = root / rel
        if not path.exists() or rel.startswith(TEMPLATE_PREFIXES):
            continue
        # Which links are active and relative is decided by md_common.iter_links —
        # the same rule the link graph in docs_orphan_scan.py uses.
        for no, href in iter_links(path):
            checked += 1
            path_part, _, frag = href.partition("#")
            target = (path.parent / path_part).resolve() if path_part else path.resolve()
            if not target.exists():
                findings.append(f"totes-ziel {rel}:{no} -> {href}")
                continue
            if frag and target.suffix == ".md":
                if frag.lower() not in {slug(h) for h in headings(target)}:
                    findings.append(f"toter-anker {rel}:{no} -> {href}")
    return findings, checked


def check_generated(root: Path) -> list[str]:
    """Generated reference pages that no longer match their source (TODO 1ab3ad21).

    Asks `scripts/docs-reference.py --check`. A repo without the sources and without the pages
    (fixtures) is not checked by the generator itself — it then reports nothing.
    """
    if not REFERENCE_SCRIPT.is_file():
        return []
    proc = subprocess.run([sys.executable, str(REFERENCE_SCRIPT), "--check", "--root", str(root)],
                          capture_output=True, text=True, check=False)
    if proc.returncode == 0:
        return []
    findings = [f"veraltet-erzeugt {line.partition(':')[2].strip()} (python3 scripts/docs-reference.py --write)"
                for line in proc.stdout.splitlines() if line.startswith("veraltet:")]
    findings += [f"referenz-fehler {line.partition(':')[2].strip()}"
                 for line in proc.stderr.splitlines() if line.startswith("fehler:")]
    if not findings:
        detail = (proc.stderr or proc.stdout).strip().splitlines()
        findings.append(f"referenz-pruefung exit {proc.returncode}: {detail[-1] if detail else 'ohne Ausgabe'}")
    return findings


def check_en_to_de(root: Path, files: list[str]) -> list[str]:
    """English pages that link to a German-only docs page (TODO 1b84ecab).

    English are README.md and everything under docs/en/. A link counts if its target
    lies under docs/ but not under docs/en/ — the English reader then lands on
    German. This is a finding for the audit, not a reason for a red gate: the gap
    is known and pending as translation work, not as an error in the commit.
    """
    docs_dir, en_dir = (root / "docs").resolve(), (root / "docs" / "en").resolve()
    hits: list[str] = []
    for rel in files:
        if rel != "README.md" and not rel.startswith("docs/en/"):
            continue
        path = root / rel
        if not path.exists():
            continue
        for no, href in iter_links(path):
            path_part = href.partition("#")[0]
            if not path_part:
                continue
            target = (path.parent / path_part).resolve()
            if not target.exists() or not target.is_relative_to(docs_dir) or target.is_relative_to(en_dir):
                continue
            # Only pages are German or English; measurement data (JSON), images etc. are
            # language-neutral and need no counterpart (TODO b94beaed).
            if target.suffix != ".md":
                continue
            hits.append(f"en-verweist-auf-deutsch {rel}:{no} -> {target.relative_to(root.resolve()).as_posix()}")
    return hits


def check_parity(root: Path) -> tuple[list[str], list[str]]:
    """Returns (new findings, known gaps) for docs/ and MIRRORED_SUBDIRS."""
    if not (root / "docs").is_dir():
        return [], []
    new: list[str] = []
    known: list[str] = []
    for sub in ("", *MIRRORED_SUBDIRS):
        _check_dir_pair(root, sub, new, known)
    return new, known


def _check_dir_pair(root: Path, sub: str, new: list[str], known: list[str]) -> None:
    """Compares docs/<sub>/ with docs/en/<sub>/: files and sequence of heading levels.

    Keys for KNOWN_GAPS are `docs/<sub>/<file>`, for KNOWN_SECTION_GAPS
    `<sub>/<file>::<heading>` (in the top folder without `<sub>/`).
    """
    de_dir = root / "docs" / sub if sub else root / "docs"
    en_dir = root / "docs" / "en" / sub if sub else root / "docs" / "en"
    if not de_dir.is_dir():
        return
    prefix = f"{sub}/" if sub else ""
    de_names = {p.name for p in de_dir.glob("*.md")}
    en_names = {p.name for p in en_dir.glob("*.md")} if en_dir.is_dir() else set()

    for name in sorted(de_names - en_names):
        key = f"docs/{prefix}{name}"
        if key in KNOWN_GAPS:
            known.append(f"kein-en-gegenstueck {key} (bekannt, TODO {KNOWN_GAPS[key]})")
        else:
            new.append(f"kein-en-gegenstueck {key}")
    for name in sorted(en_names - de_names):
        new.append(f"nur-englisch docs/en/{prefix}{name}")

    for name in sorted(de_names & en_names):
        de, en = sections(de_dir / name), sections(en_dir / name)
        # Same level sequence: nothing to pair. Whether a heading is translated or replaced by
        # another cannot be told reliably from the text alone.
        if [_level(h) for h, _ in de] == [_level(h) for h, _ in en]:
            continue
        label = f"{prefix}{name}"
        only_de, only_en = align_sections(de, en)
        for k in only_de:
            heading = de[k][0]
            key = f"{label}::{heading}"
            if key in KNOWN_SECTION_GAPS:
                known.append(f"abschnitt-fehlt-en {label} '{heading}' (bekannt, TODO {KNOWN_SECTION_GAPS[key]})")
            else:
                new.append(f"abschnitt-fehlt-en {label} '{heading}'{_position(de, k)}")
        for k in only_en:
            new.append(f"abschnitt-nur-en {label} '{en[k][0]}'{_position(en, k)}")


# ---------------------------------------------------------------------------
# Pairing sections (TODO 2d553479)
#
# The first version compared only the sequence of levels (difflib over "##", "###" …). If a
# "##" section is missing, that is ambiguous -- any section of the same rank could be missing --, and
# difflib always took the last. Twice the wrong section therefore ended up in
# KNOWN_SECTION_GAPS (see there).
#
# Now the sections are paired by their content: an alignment (dynamic
# programming) over both sequences that preserves order, pairs only equal levels and maximizes the
# sum of similarities. Similar means:
#
# - the heading -- same words ("Workflow Chains", "(V39)", `goals`) or a cognate
#   ("Architektur"/"Architecture");
# - or the section text -- language-neutral tokens in it: code in backticks, link targets,
#   identifiers with a digit, underscore, dot, slash or camel case. They look the same
#   in both languages even when the heading is fully translated.
#
# Each pair also gets a small base value (PAIR_BASE), so that two sections without any
# similarity are still preferably paired rather than both counting as a gap. It is small enough
# that a real similarity outweighs a shift. Without any signal (pure prose, fully
# translated headings) the choice remains a guess -- then, as before, the
# later section counts as missing. Probe on the 2026-09-26 stock: per file with the same level sequence
# every English section removed individually; 1058 of 1086 gaps were named correctly
# (level sequence alone: 248). The misses were pure prose (docs/konzepte: "Wofuer taugt das?"
# next to "Vorteile") or nearly identical neighbours (two endpoints of the same resource).
#
# Hence, since TODO 3fbff015, two fine signals that only decide close cases (each at most
# TIE_WEIGHT, smaller than any real similarity):
#
# - the shape of the section: text length, lines, list items, table rows. A translation
#   keeps it almost unchanged; the length is adjusted by the typical EN/DE ratio (English is slightly
#   shorter). This separates prose sections that nothing else connects.
# - the heading even when the text already matches fully: "…/enable" and "…/disable" have
#   the same text, but only one matching heading.
#
# In addition, small sets of language-neutral tokens that are EQUAL (both just `263`) count half:
# Until then those got 0, while a larger neighbouring section with the same number in it
# got a Jaccard value -- it pulled the section towards itself. Probe on the 2026-10-01 stock as above: 1213
# of 1213 (the same probe with the previous version: 1184). The cases from back then are in
# StockPairingTest in scripts/tests/test_docs_parity_check.py.
# ---------------------------------------------------------------------------
PAIR_BASE = 0.1
TIE_WEIGHT = 0.05
SMALL_EQUAL_SET = 0.5
# English is shorter: characters EN/DE per file pair on the 2026-10-01 stock between 0.93 and 0.99,
# median 0.965. Deliberately a constant, not a value per file: that one is distorted by the missing
# section (in docs/konzepte by a sixth), and with it the assignment tipped.
LENGTH_RATIO_EN_DE = 0.96
_HEADING_WORD = re.compile(r"[a-z0-9_.]+")
_CODE_SPAN = re.compile(r"`([^`\n]+)`")
_LINK_TARGET = re.compile(r"\]\(([^)\s]+)\)")
_TOKEN = re.compile(r"[A-Za-z0-9_./:-]+")
_NEUTRAL = re.compile(r"[0-9_/]|[a-z][A-Z]|\.[a-z]")
_LIST_ITEM = re.compile(r"(?:[-*+]|\d+\.)\s")


def sections(path: Path) -> list[tuple[str, str]]:
    """(Heading, section text up to the next heading) -- fence-aware like headings()."""
    out: list[tuple[str, list[str]]] = []
    fence = False
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        stripped = line.lstrip()
        if FENCE.match(line):
            fence = not fence
        elif not fence and stripped.startswith("#") and not stripped.startswith("#!"):
            out.append((stripped, []))
            continue
        if out:
            out[-1][1].append(line)
    return [(heading, "\n".join(body)) for heading, body in out]


def _level(heading: str) -> str:
    return heading.split(" ")[0]


def _heading_text(heading: str) -> str:
    return heading.lstrip("#").strip().lower()


def _jaccard(a: set[str], b: set[str]) -> float:
    shared = len(a & b)
    return shared / (len(a) + len(b) - shared) if a and b else 0.0


def _neutral_tokens(body: str) -> set[str]:
    tokens = {code.strip() for code in _CODE_SPAN.findall(body)}
    tokens.update(target.split("#")[0] for target in _LINK_TARGET.findall(body))
    for word in _TOKEN.findall(body):
        word = word.strip(".:-/")
        if len(word) >= 3 and _NEUTRAL.search(word):
            tokens.add(word)
    tokens.discard("")
    return tokens


def _shape(body: str) -> tuple[int, int, int, int]:
    """Shape of a section: characters, lines, list items, table rows (without blank lines)."""
    lines = [line.strip() for line in body.splitlines() if line.strip()]
    return (sum(len(line) for line in lines), len(lines),
            sum(1 for line in lines if _LIST_ITEM.match(line)),
            sum(1 for line in lines if line.startswith("|")))


def _shape_similarity(de: tuple[int, ...], en: tuple[int, ...]) -> float:
    """Mean of the smaller/larger ratios per feature; the DE length times LENGTH_RATIO_EN_DE."""
    values = (de[0] * LENGTH_RATIO_EN_DE, *de[1:])
    return sum((min(a, b) + 1) / (max(a, b) + 1) for a, b in zip(values, en)) / len(en)


def _features(section: tuple[str, str]) -> tuple:
    """Level, heading text, its words, the language-neutral tokens and the shape."""
    heading, body = section
    text = _heading_text(heading)
    return (_level(heading), text, {w for w in _HEADING_WORD.findall(text) if len(w) >= 2},
            _neutral_tokens(body), _shape(body))


def _similarity(de: tuple, en: tuple, matcher: difflib.SequenceMatcher) -> float:
    """Similarity of two sections of the same level; matcher already carries en[1] as second sequence."""
    words = _jaccard(de[2], en[2])
    # Below three tokens a hit is chance -- a single `true` makes no kinship.
    # If the small sets match completely, though, that counts half (see header).
    if len(de[3] | en[3]) >= 3:
        body = _jaccard(de[3], en[3])
    else:
        body = SMALL_EQUAL_SET if de[3] and de[3] == en[3] else 0.0
    # Letters compare only if no word matches: for cognates ("Architektur"/"Architecture").
    # If the headings share words, those say more -- and the API reference with its hundreds of
    # similar endpoint headings would otherwise become a computation task. Only from 0.6, below that
    # it hits random letters ("Eins"/"One").
    letters = 0.0
    if not words:
        matcher.set_seq1(de[1])
        if matcher.real_quick_ratio() >= 0.6 and matcher.quick_ratio() >= 0.6:
            ratio = matcher.ratio()
            letters = ratio if ratio >= 0.6 else 0.0
    tie = TIE_WEIGHT * (_shape_similarity(de[4], en[4]) + words) / 2
    return max(words, body, letters) + tie


def align_sections(de: list[tuple[str, str]], en: list[tuple[str, str]]) -> tuple[list[int], list[int]]:
    """Pairs the sections of both languages; returns (DE without partner, EN without partner) as indices."""
    return align_scores(pair_scores(de, en))


def pair_scores(de: list[tuple[str, str]], en: list[tuple[str, str]]) -> list[list[float | None]]:
    """Value of each possible pair (DE index, EN index); None where the levels differ."""
    features_de = [_features(section) for section in de]
    score: list[list[float | None]] = [[None] * len(en) for _ in de]
    for j, feature_en in enumerate(_features(section) for section in en):
        matcher = difflib.SequenceMatcher(None)
        matcher.set_seq2(feature_en[1])  # second sequence once per heading, difflib caches it
        for i, feature_de in enumerate(features_de):
            if feature_de[0] == feature_en[0]:
                score[i][j] = PAIR_BASE + _similarity(feature_de, feature_en, matcher)
    return score


def align_scores(score: list[list[float | None]]) -> tuple[list[int], list[int]]:
    """The order-preserving pairing with the highest sum; (rows without partner, columns without partner)."""
    n = len(score)
    m = len(score[0]) if score else 0
    # best[i][j]: highest sum for the remaining sequences de[i:] and en[j:].
    best = [[0.0] * (m + 1) for _ in range(n + 1)]
    for i in range(n - 1, -1, -1):
        for j in range(m - 1, -1, -1):
            value = max(best[i + 1][j], best[i][j + 1])
            if score[i][j] is not None:
                value = max(value, score[i][j] + best[i + 1][j + 1])
            best[i][j] = value
    # Walk back from the front; on a tie a pair beats a gap, a German gap beats
    # an English one. So the guess without a signal falls on the later section.
    only_de: list[int] = []
    only_en: list[int] = []
    i = j = 0
    close = 1e-9
    while i < n and j < m:
        if score[i][j] is not None and abs(best[i][j] - (score[i][j] + best[i + 1][j + 1])) < close:
            i, j = i + 1, j + 1
        elif abs(best[i][j] - best[i + 1][j]) < close:
            only_de.append(i)
            i += 1
        else:
            only_en.append(j)
            j += 1
    only_de.extend(range(i, n))
    only_en.extend(range(j, m))
    return only_de, only_en


def _position(items: list[tuple[str, str]], k: int) -> str:
    """Where the section is: number of the heading and its predecessor in the same file."""
    after = f", nach '{items[k - 1][0]}'" if k > 0 else ""
    return f" (Ueberschrift {k + 1} von {len(items)}{after})"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=None)
    args = parser.parse_args()
    root = Path(args.root).resolve() if args.root else Path(
        subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True,
                       text=True, check=False).stdout.strip() or "."
    ).resolve()

    files = tracked_markdown(root)
    link_findings, checked = check_links(root, files)
    parity_new, parity_known = check_parity(root)
    en_to_de = check_en_to_de(root, files)
    generated = check_generated(root)
    findings = link_findings + parity_new + generated

    print("## Doku-Verweise und DE/EN-Gleichstand")
    print(f"markdown_files: {len(files)}")
    print(f"relative_links_checked: {checked}")
    print(f"findings: {len(findings)}")
    print(f"known_gaps: {len(parity_known)}")
    for item in parity_known:
        print(f"bekannt: {item}")
    for item in findings:
        print(f"BEFUND: {item}")
    # Only reported, not counted: see check_en_to_de.
    print(f"en_links_to_german: {len(en_to_de)}")
    for item in en_to_de:
        print(f"HINWEIS: {item}")

    print()
    print("## Gate status")
    if findings:
        print("gate_status: YELLOW")
        print("gate_category: documentation-links")
        print("gate_description: Tote Verweise, neue DE/EN-Luecken oder veraltete erzeugte Referenzen"
              " in der Doku.")
        print("todo_item: Tote Verweise, DE/EN-Luecken oder veraltete Referenzen in der Doku beheben | MEDIUM |"
              " documentation,release | docs_parity_check.py meldet neue Befunde.")
        return 1
    print("gate_status: GREEN")
    print("gate_category: documentation-links")
    print("gate_description: Keine toten Verweise, keine neuen DE/EN-Luecken, erzeugte Referenzen aktuell.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
